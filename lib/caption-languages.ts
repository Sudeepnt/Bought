export type CaptionLanguageCode =
  (typeof ALL_CAPTION_LANGUAGES)[number]['code'];

export const FEATURED_CAPTION_LANGUAGE_CODES = [
  'en',
  'zh',
  'es',
  'fr',
  'bn',
  'pt',
  'ru',
  'id',
  'de',
  'ja',
] as const satisfies readonly CaptionLanguageCode[];

const featuredCodes = new Set<string>(FEATURED_CAPTION_LANGUAGE_CODES);

export const FEATURED_CAPTION_LANGUAGES = FEATURED_CAPTION_LANGUAGE_CODES.map(
  (code) => ALL_CAPTION_LANGUAGES.find((language) => language.code === code)!,
);

export const OTHER_CAPTION_LANGUAGES = ALL_CAPTION_LANGUAGES.filter(
  ({ code }) => !featuredCodes.has(code),
).sort((a, b) => a.label.localeCompare(b.label));

export function isCaptionLanguageCode(
  language: string,
): language is CaptionLanguageCode {
  return ALL_CAPTION_LANGUAGES.some(({ code }) => code === language);
}

export function captionLanguageBaseCode(language: string | undefined) {
  return language?.trim().toLowerCase().split('-')[0] ?? '';
}
